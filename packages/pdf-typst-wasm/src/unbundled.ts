// @junejs/pdf-typst-wasm/unbundled — the renderer without its engine file (#383). The default
// entries embed typst.wasm (bun.ts imports it as a file, workerd.ts as a module), so a
// `bun build --compile` binary carries its 29 MiB whether or not it ever renders. This entry
// never references the file: the app passes `load`, and the engine is fetched, read or taken
// from a cache only on the first render.
//
//   import { typstWasmRenderer } from "@junejs/pdf-typst-wasm/unbundled";
//   typstWasmRenderer({ load: (ref) => myCache.get(ref) });
//
// The engine's ref (size, sha256, URLs) is generated by scripts/build-wasm.ts from the file
// being published, since a local build's bytes differ from CI's. loadVerified checks the
// loader's bytes against it, so an engine that doesn't match the release is never run. In a
// checkout without a build there is no ref, and the first render says so.
//
// Runtime-neutral: no host imports, so the same file serves Node, Bun, Deno and workerd.

import { loadVerified, type AssetLoader, type AssetRef } from "./assets";
import type { FontEgress } from "./fonts";
import { createTypstWasmRenderer, type TypstWasmRenderer, type TypstWasmRendererOptions } from "./renderer";

export { loadVerified, type AssetLoader, type AssetRef } from "./assets";
export { googleFontSubsets, localFonts, type DocumentFonts, type FontEgress, type FontProvider, type FontSource, type GoogleFont } from "./fonts";
export { createEngine, TypstCompileError, type FontScope, type TypstEngine, type TypstOutput, type WasmSource } from "./engine";
export type { TypstWasmRenderer } from "./renderer";

// Where a release's engine can be fetched: the npm tarball's own file, through two CDNs that
// serve npm packages. The sha256 makes either as good as the other.
export function engineUrls(version: string): string[] {
  return [`https://cdn.jsdelivr.net/npm/@junejs/pdf-typst-wasm@${version}/dist/typst.wasm`, `https://unpkg.com/@junejs/pdf-typst-wasm@${version}/dist/typst.wasm`];
}

const ENGINE_HOSTS: FontEgress[] = engineUrls("0").map((url) => ({ host: new URL(url).host, sends: "nothing" }));

// The ref of the engine this release ships. Rejects in a checkout that hasn't run
// `bun run build`.
export async function typstWasmAsset(): Promise<AssetRef> {
  try {
    // @ts-ignore — written by scripts/build-wasm.ts; absent until the engine is built.
    return (await import("../dist/typst.wasm.ref.json", { with: { type: "json" } })).default as AssetRef;
  } catch (err) {
    throw new Error("@junejs/pdf-typst-wasm/unbundled: dist/typst.wasm.ref.json is missing — in the June repo, run `bun run build` in packages/pdf-typst-wasm", { cause: err });
  }
}

export type UnbundledRendererOptions = Omit<TypstWasmRendererOptions, "wasm"> & {
  // Gets the engine's bytes for its ref, on the first render. They are checked against the
  // ref's size and sha256 before they run.
  load: AssetLoader;
  // What `load` contacts, for renderer.egress. Default: the ref's URL hosts, sending nothing
  // (the engine may be downloaded). [] when the app pre-seeds it and never fetches.
  engineEgress?: FontEgress[];
};

export function typstWasmRenderer(opts: UnbundledRendererOptions): TypstWasmRenderer {
  const { load, engineEgress, ...rest } = opts;
  return createTypstWasmRenderer(async () => loadVerified(await typstWasmAsset(), load), rest, engineEgress ?? ENGINE_HOSTS);
}
