// Generates src/bidi-classes.ts: the code points whose Unicode Bidi_Class is strong — L, or R/AL
// — as sorted ranges, from the UCD's DerivedBidiClass.txt, pinned by version and sha256. The
// PDF converter picks a paragraph's direction the way the Unicode bidi algorithm's rule P2
// does, from its first strong character (#392), and JavaScript regexes have no Bidi_Class.
// Unassigned code points take the file's @missing defaults (the unassigned rest of the Hebrew
// block is R), so text from a newer Unicode still lands right.
//
//   bun scripts/gen-bidi.ts   (from packages/pdf; needs the network)

import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const VERSION = "17.0.0";
const SHA256 = "4867b4b7f0731ed1bfcd34cc6251211ff1542541fce0734b6fbda139ee80b3a4";
const URL_ = `https://www.unicode.org/Public/${VERSION}/ucd/extracted/DerivedBidiClass.txt`;

const res = await fetch(URL_);
if (!res.ok) throw new Error(`${URL_}: HTTP ${res.status}`);
const text = await res.text();
const got = createHash("sha256").update(text).digest("hex");
if (got !== SHA256) throw new Error(`DerivedBidiClass.txt: sha256 ${got}, expected ${SHA256}`);

const N = 0x110000;
const cls = new Array<string>(N).fill("L"); // the file's own first default
const LONG: Record<string, string> = { Left_To_Right: "L", Right_To_Left: "R", Arabic_Letter: "AL" };
const span = (s: string) => s.split("..").map((h) => parseInt(h, 16)) as [number, number?];
for (const line of text.split("\n")) {
  const missing = /^#\s*@missing:\s*([0-9A-F.]+);\s*(\w+)/.exec(line);
  const data = /^([0-9A-F.]+)\s*;\s*(\w+)/.exec(line);
  const m = missing ?? data;
  if (!m) continue;
  const [a, b = a] = span(m[1]!);
  const value = LONG[m[2]!] ?? m[2]!;
  for (let i = a; i <= b; i++) cls[i] = value;
}

// [start, end, rtl] runs of strong code points; anything outside them is weak or neutral.
const runs: [number, number, 0 | 1][] = [];
for (let i = 0; i < N; i++) {
  const dir = cls[i] === "L" ? 0 : cls[i] === "R" || cls[i] === "AL" ? 1 : -1;
  if (dir < 0) continue;
  const last = runs.at(-1);
  if (last && last[1] === i - 1 && last[2] === dir) last[1] = i;
  else runs.push([i, i, dir as 0 | 1]);
}

const rows: string[] = [];
for (let i = 0; i < runs.length; i += 6) rows.push("  " + runs.slice(i, i + 6).map(([a, b, r]) => `0x${a.toString(16)}, 0x${b.toString(16)}, ${r},`).join(" "));
const out = `// Generated by scripts/gen-bidi.ts from Unicode ${VERSION} DerivedBidiClass.txt — do not edit.
// Strong bidi classes as flat [start, end, rtl] triples, sorted: rtl 0 is L, 1 is R or AL.
export const UNICODE_VERSION = "${VERSION}";
export const STRONG: readonly number[] = [
${rows.join("\n")}
];
`;
const target = join(dirname(fileURLToPath(import.meta.url)), "../src/bidi-classes.ts");
writeFileSync(target, out);
console.log(`src/bidi-classes.ts: ${runs.length} runs (${runs.filter((r) => r[2]).length} right-to-left), Unicode ${VERSION}`);
